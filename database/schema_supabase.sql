-- ====================================================================
-- SISTEMA DE GESTION: LA ESCUELITA GERMAN SIMAN
-- SCRIPT OPTIMIZADO PARA SUPABASE (POSTGRESQL CLOUD)
-- ====================================================================

-- 1. TABLA: ALUMNOS
CREATE TABLE IF NOT EXISTS public.alumnos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    apellido TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    telefono TEXT,
    fecha_nacimiento DATE,
    fecha_creacion TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. TABLA: CURSOS
CREATE TABLE IF NOT EXISTS public.cursos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    descripcion TEXT,
    costo NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    periodo_pago TEXT NOT NULL DEFAULT 'Mensual',
    dia_vencimiento INT DEFAULT 10,
    fecha_limite_pago DATE NULL,
    activo BOOLEAN DEFAULT TRUE NOT NULL,
    fecha_creacion TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. TABLA: INSCRIPCIONES (Asignación de alumnos a cursos)
CREATE TABLE IF NOT EXISTS public.inscripciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alumno_id BIGINT NOT NULL REFERENCES public.alumnos(id) ON DELETE CASCADE,
    curso_id BIGINT NOT NULL REFERENCES public.cursos(id) ON DELETE CASCADE,
    fecha_inscripcion DATE NOT NULL DEFAULT CURRENT_DATE,
    estado TEXT DEFAULT 'Activo' NOT NULL,
    observaciones TEXT,
    fecha_creacion TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    CONSTRAINT uq_alumno_curso UNIQUE (alumno_id, curso_id)
);

-- ====================================================================
-- CONFIGURACION DE ACCESO PARA LA API DE SUPABASE (CLAVE ANON)
-- ====================================================================
-- Deshabilitamos RLS para permitir que la app gestione las tablas directamente con la clave anon:
ALTER TABLE public.alumnos DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.cursos DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.inscripciones DISABLE ROW LEVEL SECURITY;

-- Otorgar permisos completos a los roles de Supabase:
GRANT ALL ON TABLE public.alumnos TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.cursos TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.inscripciones TO anon, authenticated, service_role;

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

